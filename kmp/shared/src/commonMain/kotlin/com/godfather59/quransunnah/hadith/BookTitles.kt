/**
 * Display title for a hadith book/section. Arabic UI labels when the app
 * language is Arabic, source English title otherwise (never blank: falls
 * back to the number range when even that is missing).
 */
fun bookDisplayTitle(
    collectionId: String,
    section: Int,
    sourceTitle: String,
    language: String,
    first: Int = 0,
    last: Int = 0,
): String {
    if (language == "ar") {
        bookTitlesAr[collectionId]?.get(section)?.let { return it }
    }
    if (sourceTitle.isNotBlank()) return sourceTitle
    return "$first–$last"
}
